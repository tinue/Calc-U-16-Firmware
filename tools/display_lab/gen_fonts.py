#!/usr/bin/env python3
"""Generate firmware/calc/src/fonts.rs from the display lab's fonts.

    python3 tools/display_lab/gen_fonts.py
"""
import pathlib

import lab

OUT = pathlib.Path(__file__).resolve().parents[2] / "firmware" / "calc" / "src" / "fonts.rs"

FONTS = [
    ("F5", "5×7 regular: digits, capitals, a few symbols", lab.F5A, lambda c: not c.islower()),
    ("F4", "4×7 condensed: digits and HEX capitals", lab.F4C, lambda c: not c.islower()),
    ("F3", "3×5 small: digits, capitals, base suffixes (h d o b), f/g", lab.F3A, lambda c: True),
]


def columns(rows):
    return [sum(1 << r for r, row in enumerate(rows) if row[k] == "#") for k in range(len(rows[0]))]


def main():
    out = [
        "//! Pixel fonts. Generated by tools/display_lab/gen_fonts.py from the display lab; do not edit.",
        "//!",
        "//! Each glyph is a list of columns, bit 0 = top row.",
        "",
        "use crate::display::Font;",
        "",
    ]
    for name, doc, font, keep in FONTS:
        h = len(font["0"])
        out.append(f"/// {doc}.")
        out.append(f"pub static {name}: Font = Font {{")
        out.append(f"    height: {h},")
        out.append("    glyphs: &[")
        for c in sorted(c for c in font if keep(c)):
            cols = ", ".join(f"0x{b:02X}" for b in columns(font[c]))
            lit = "b'\\''" if c == "'" else f"b'{c}'"
            out.append(f"        ({lit}, &[{cols}]),")
        out.append("    ],")
        out.append("};")
        out.append("")
    OUT.write_text("\n".join(out))
    print(OUT)


if __name__ == "__main__":
    main()
